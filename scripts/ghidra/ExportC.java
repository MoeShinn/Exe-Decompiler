// Export per-function pseudo-C using Ghidra's decompiler.
// Args: <output dir> <time budget in seconds>
import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import java.io.File;
import java.io.PrintWriter;

public class ExportC extends GhidraScript {
    private static final int PER_FILE = 500;

    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        File out = new File(args[0]);
        long deadline = System.currentTimeMillis() + Long.parseLong(args[1]) * 1000L;
        out.mkdirs();

        DecompInterface di = new DecompInterface();
        di.openProgram(currentProgram);
        PrintWriter w = null;
        int n = 0;
        try {
            FunctionIterator it = currentProgram.getFunctionManager().getFunctions(true);
            while (it.hasNext() && !monitor.isCancelled()) {
                if (System.currentTimeMillis() > deadline) {
                    println("Time budget exhausted, stopping export.");
                    break;
                }
                Function f = it.next();
                DecompileResults r = di.decompileFunction(f, 60, monitor);
                if (!r.decompileCompleted()) {
                    continue;
                }
                if (n % PER_FILE == 0) {
                    if (w != null) {
                        w.close();
                    }
                    w = new PrintWriter(new File(out, String.format("part_%04d.c", n / PER_FILE + 1)), "UTF-8");
                    w.println("// Pseudo-C generated by Ghidra. Not the original source code.");
                    w.println();
                }
                w.println("// " + f.getName() + " @ " + f.getEntryPoint());
                w.println(r.getDecompiledFunction().getC());
                n++;
            }
        } finally {
            if (w != null) {
                w.close();
            }
            di.dispose();
        }
        println("Exported " + n + " functions.");
    }
}
